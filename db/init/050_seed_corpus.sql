## 7. 우리 서비스가 도움이 됐을 지점 / 도움이 안 됐을 지점

### 도움이 됐을 지점

1. **"문제된 입금의 일자·시각을 먼저 특정하라"는 절차 지식의 선제 제공.** 이 글쓴이는 스스로 캐물어 알아냈지만 대부분의 명의인은 이 발상 자체를 못 한다. 첫 단계에서 "정지 사유가 된 입금 건의 일시·금액·입금자명을 은행/수사기관에 확인하라"고 안내하면 증거 수집의 출발점이 열린다.
2. **플랫폼 거래내역 발급 요청문 자동 생성.** 넥슨 고객센터, 당근마켓, 번개장터, 중고나라 등에 "몇 년 몇 월 며칠 거래내역을 수사기관 제출용으로 발급해 달라"고 보내는 정형 요청문을 만들어 주면 B분류 증거 확보가 자동화된다. 이 사례에서 **B가 승부를 갈랐다**는 점에서 우선순위가 매우 높은 기능이다.
3. **C분류(생활계좌 소명)를 빠뜨리지 않게 강제.** 글쓴이는 우연히 "급여통장 + 명함"을 챙겼고 그것이 인상을 결정적으로 바꿨다. 재직증명서·급여이체 이력이 보이는 장기 거래내역까지 체크리스트로 요구하면 구두 진술 수준을 문서 수준으로 끌어올릴 수 있다.
4. **3자사기 구조 설명문의 문서화.** "차분하고 덤덤하게 구조 설명"은 말솜씨에 의존한다. 도식과 서술을 갖춘 표준 문단을 제공하면 말주변 없는 사람도 같은 수준의 설명을 서면으로 낼 수 있다.
5. **D분류 공백 메우기.** 사기범 고소장 초안, 사기범 식별정보(계정·캐릭터명·연락처) 정리표를 함께 만들어 주면 "나도 피해자"라는 지위가 문서로 남는다.
6. **최초 접촉 대응 안내.** "수사기관 연락은 피싱이 아닐 수 있으니 소속·직위·사건번호를 확인한 뒤 대표번호로 역발신하라"는 짧은 안내만으로 이 사례의 첫 실수를 막을 수 있다.

### 도움이 안 됐을 지점

1. **가장 결정적: 은행 이의제기 국면이 아예 존재하지 않았다.** 우리 핵심 산출물인 "은행 제출용 지급정지 이의제기 소명서"는 이 사례에서 제출할 곳이 없다. 필요했던 건 경찰 조사 대응 문서다.
2. **유입 트리거가 다르다.** 우리 서비스는 "지급정지 문자 수신"을 진입점으로 상정하는데, 이 사용자는 경찰 전화로 사건을 인지했다. 이 경로의 사용자는 우리 서비스를 찾아오지 않는다.
3. **거래 목적물이 실물이 아니다.** 택배 송장·직거래 사진·물품 사진 같은 우리 표준 B증거 체크리스트가 통째로 무용하고, 게임 운영사 로그라는 전혀 다른 발급 경로가 필요하다. 현행 기획이 실물 중고거래만 상정하면 이런 케이스를 받지 못한다.
4. **대면 상황의 태도·톤 관리는 서비스 범위 밖이다.** 이 사례에서 초반 분위기를 망친 것은 문서 부실이 아니라 욕설이었다.
5. **문서 작성 실력이 병목이 아니었다.** 이 사용자에게 부족했던 것은 글이 아니라 절차 지식과 증거였다. 우리 서비스의 실제 가치가 "AI 글쓰기"보다 **"무엇을 어디서 받아 와야 하는지 알려주는 체크리스트"**에 있음을 시사한다.

