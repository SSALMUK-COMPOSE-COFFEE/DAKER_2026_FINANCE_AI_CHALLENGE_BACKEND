## 5. 증거 4분류 매핑

| 분류 | 글쓴이가 제시한 증거 | 평가 |
|---|---|---|
| **A. 거래가 실재했다** | ① 수사관에게 캐물어 특정한 **문제 입금 건의 일자·시각** ② 해당 일자 **본인 통장 거래내역 출력본** ③ 넥슨 발급 게임 내 거래내역(입금 시각과의 시간적 근접성) | **부분 충족.** 입금 사실과 시각은 입증됐지만, **거래 성립 자체를 보여주는 증거(구매자와 주고받은 대화, 가격 합의, 계좌번호를 알려준 기록)가 전무**하다. "외치기"(게임 내 전체채팅) 모집이라 로그가 남지 않았거나 보존하지 않은 것으로 보인다. A의 절반이 비어 있다. |
| **B. 물건을 실제로 넘겼다** | **넥슨 고객센터에서 발급받은 해당 일자 게임 내 거래내역 출력본** | **강하게 충족. 이 사례의 킬러 증거.** 게임 운영사라는 **이해관계 없는 제3자가 발급한 객관적 시스템 로그**로, 누가 누구에게 언제 무엇을 넘겼는지가 남았다. 실물 중고거래의 택배 송장·수령 확인에 정확히 대응하며, 수취인 계정이 특정된다는 점에서 증명력은 오히려 더 높다. |
| **C. 이 계좌는 원래 정상 생활계좌다** | "회사 다니고 있고 내 계좌는 **입사 후 지금까지 급여통장으로 쓰고 있다**" 진술 + **명함 제출** | **충족(다만 약식).** 계좌의 생활계좌 성격과 본인의 사회적 신원을 함께 제시한 점이 좋다. 다만 **재직증명서·급여이체 이력이 보이는 장기 거래내역 같은 문서 증빙은 없고**, 구두 진술과 명함이라는 가벼운 소명에 그쳤다. 대면 조사라 통했지만 서면 이의제기였다면 부족했을 수준이다. |
| **D. 절차 메타 / 본인도 피해자임** | 사실상 **비어 있음.** 수사관에게 "적극 협조하겠다", "넥슨에 사기범 계정 인적정보가 있으니 피해 게임과 연계하면 검거 가능하다"고 **구두로** 단서를 제공한 것이 유일 | **미충족.** 사기범에 대한 **본인 명의 고소장·피해 신고 접수증이 없고**, 사기범 계정·캐릭터명·연락처를 정리한 문서도 제출하지 않았다. 본인 역시 재화를 잃은 피해자라는 지위를 서면화하지 않았다. 협조 의사가 구두에 그친 탓에 이후 아무 연락도 오지 않았다. |

**요약**: **B가 압도적으로 강하고, C는 진술 수준으로 충족, A는 절반만, D는 공백.**
대면 참고인조사에서는 B 하나로 충분히 통했지만, 서면 이의제기였다면 A(거래 합의 기록)와 D(본인 피해자성 증빙)의 공백이 그대로 약점이 됐을 것이다.

