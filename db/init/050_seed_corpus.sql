## 4. 계좌 지급정지 발생 여부

### **발생하지 않았다. 지급정지·은행 이의제기 없이 경찰 수사(참고인조사) 단계만 있었음.**

- 원문 전문 어디에도 지급정지, 계좌 동결, 은행 통지, 이의제기, 금융감독원, 채권소멸절차 개시 공고에 관한 언급이 **일절 없다**.
- 최초 인지 경로가 **은행이 아니라 경찰 전화**였다. 지급정지가 걸렸다면 통상 은행 통지·이체 불가·카드 결제 실패가 먼저 체감되고 그것이 서사의 출발점이 됐을 것이다.
- "내 통장 거래내역 당일자 쫙 프린트"는 계좌 조회·출력이 정상적으로 가능했다는 정황이다. 동결 상태에서도 조회 자체는 가능하지만, 계좌가 묶였다면 그 사실이 서사의 중심이 됐을 것이다.
- 사건이 **참고인조사 → 무인 → 종결**로 끝났고, 계좌를 되찾는 과정에 대한 서술이 전혀 없다.

**지급정지가 없었던 것으로 보이는 구조적 이유 (추정)**

선행 사기가 "모바일게임 현질 사기"라면 이는 재화·용역 공급을 가장한 거래사기이고, 통신사기피해환급법상 전기통신금융사기의 정의에서 제외될 여지가 크다. 그 경우 은행 지급정지 트랙 자체가 열리지 않고 **형사 고소 → 계좌 추적 → 참고인 조사**의 경로만 남는다. 즉 이 사례는 "잘 대응해서 지급정지를 면한 것"이 아니라 **애초에 지급정지 트랙이 아니었을 가능성**이 높다. (8장 경고 참조)

**우리 서비스와의 관계**: 「풀림」은 은행 제출용 이의제기 소명서 작성 서비스다. **이 사례에는 우리 산출물이 들어갈 자리가 없었다.** 필요했던 것은 경찰 참고인조사 대응용 진술 정리 문서였다.

