## 2. 3자사기 해당 여부 및 판단 근거

### 판단: **부분 해당**

**해당한다고 본 근거 (구조적 일치)**

1. 글쓴이(판매자)는 자기 물건(게임 내 재화)을 팔려고 불특정 구매자를 모집했다 → 정상 판매 의사.
2. 접근한 구매자가 사기범이었고, 사기범은 **자기 돈이 아닌 제3자(별개 사기 피해자)의 돈**을 글쓴이 계좌로 입금시켰다.
3. 글쓴이는 그 입금을 정상 대금으로 알고 **재화를 사기범에게 인도**했다.
4. 이후 **제3자 피해자가 신고**하면서 글쓴이 계좌가 수사선상에 올랐고, 글쓴이는 사기 공범 의심을 받는 위치에 놓였다.
5. 글쓴이 본인도 사건을 "3자사기"로 인식하고 수사관에게 그 구조를 직접 설명했다.

→ 돈의 흐름(피해자 → 명의인 계좌)과 물건의 흐름(명의인 → 사기범)이 어긋나는 전형적 삼각 구조가 그대로 성립한다.

**전형과 다른 지점 (그래서 "완전 해당"이 아닌 이유)**

| 축 | 우리가 상정한 전형 | 이 사례 |
