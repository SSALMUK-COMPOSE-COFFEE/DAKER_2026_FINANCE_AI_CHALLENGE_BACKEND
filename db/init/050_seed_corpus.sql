## 8. 경고 — 일반화하면 위험한 지점

1. **지급정지가 없었던 사례다. 지급정지 이의제기 성공 사례로 인용하면 안 된다.** 이 글은 "경찰 참고인조사에서 혐의를 벗은 이야기"이지 "묶인 계좌를 푼 이야기"가 아니다. 계좌 동결로 인한 생계 마비라는 우리 문제 정의를 뒷받침하는 근거로 쓸 수 없다.
2. **인과관계 오귀인 위험이 크다.** 글쓴이의 준비가 훌륭했던 것은 사실이나, 계좌가 안 묶인 이유는 준비가 아니라 **선행 사기 유형(게임 거래사기)이 통신사기피해환급법상 지급정지 대상이 아니었기 때문일 가능성**이 높다. "이 사람처럼 준비하면 지급정지를 피할 수 있다"는 서사는 틀렸다.
3. **거래 목적물이 게임머니라는 점에서 전형과 어긋난다.** 게임머니·아이템의 현금거래는 게임산업진흥에 관한 법률상 환전·환전 알선 금지 규정과 얽힐 소지가 있다. 이 사례를 대표 사례로 전면에 내세우면 서비스가 **별도 위법 소지가 있는 거래를 옹호하는 것처럼 보일 수 있다.** 온보딩 단계에서 거래 유형을 분기해 처리해야 한다.
4. **표본 1건, 익명 게시글, 검증 불가.** 게임 커뮤니티 무기명 후일담이라 사실 확인이 불가능하고, 실패담은 애초에 잘 올라오지 않는 **생존 편향**이 있다. 정량 근거로 쓸 수 없고 정성적 문제 인식 자료로만 써야 한다. 댓글도 0건이라 커뮤니티 검증(반박·보강)조차 없다.
5. **"참고인조사 종결 = 완전 해결"이 아니다.** 형사 절차에서 혐의를 벗어도 **피해자의 민사 부당이득반환청구는 별개**로 남는다. 3자사기에서 명의인이 형사 무혐의를 받고도 민사에서 입금액 반환 판결을 받는 경우가 드물지 않다. 원문의 "해결 끝"을 액면 그대로 인용하면 사용자에게 잘못된 기대를 준다.
6. **재현을 권할 수 없는 행동이 섞여 있다.** 수사관에게 욕설하고 출석 당일 "윽박지른" 행위는 결과적으로 문제가 되지 않았을 뿐, 어떤 경우에도 서비스가 권할 수 있는 대응이 아니다.
7. **"1,000억"은 원화가 아니다.** 게임 내 화폐 "시드" 기준 액수이며 실제 현금 거래 규모는 원문에 특정되지 않는다. 피해 규모 통계에 넣으면 안 된다.
8. **신고자가 보이스피싱 피해자가 아닐 수 있다.** 원문상 신고자는 "모바일게임 현질" 관련 사기 피해자다. 보이스피싱을 전제로 한 우리 서사와 다르며, 3자사기의 상위 유형이 보이스피싱만이 아니라 **온라인 거래사기 전반**임을 보여준다. 서비스 범위 정의에 반영할 필요가 있다.

