## 2. 사건 구조 (시간순)

**등장인물**
- **글쓴이(명의인/판매자)** — 커뮤니티에 25만원짜리 물건을 올린 사람
- **사기범** — 쪽지로 접근한 "구매자". 동시에 제3자에게 "뭘 팔겠다"고 접근한 판매자 행세
- **제3자(진짜 피해자/고소인)** — 사기범에게 물건을 사려고 돈을 보낸 사람. 글쓴이와 일면식 없음

**경로**
1. 글쓴이, 커뮤니티에 물건 25만원에 판매 등록
2. 사기범이 **문자가 아닌 쪽지**로 구매 의사 전달 (1차 이상신호)
3. 집 근처 역 안 대면 직거래로 약속 → 글쓴이 안심
4. 사기범이 **대면 거래인데도 계좌 입금을 고집**하며 계좌번호 요구 (2차 이상신호)
5. 같은 시기 사기범 → 제3자에게 물건 판매를 미끼로 접근, **글쓴이 계좌번호를 자기 계좌인 양 알려줌**
6. 제3자 → 글쓴이 계좌로 **40만원 입금**
7. 글쓴이, 25만원 물건값보다 15만원 초과 입금된 것을 "상대의 실수"로 오인 (3차 이상신호)
8. 글쓴이, **현금 15만원을 인출**해 물건과 함께 지참, 역에서 사기범에게 **물건 + 현금 15만원 인도**. "돈 보내고 이런거 실수하시면 안 된다"고 친절히 조언까지 함
9. 사기범 잠적
10. **몇 달 뒤** 글쓴이 집으로 고소장(또는 유사 서면) 도달. 고소인은 모르는 사람 이름
11. 경찰서 출석 → 담당자가 "이러이러한 사람이 뭘 산다고 돈을 보냈는데 당신이 잠수를 타서 사기로 고소했다"고 설명
12. 글쓴이, 그 자리에서 구조를 파악하고 소명자료 제출
13. **얼마 뒤 무혐의 처분**

