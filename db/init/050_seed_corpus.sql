## 5. 은행·경찰의 실제 응대

**은행**: **접점 자체가 없음.** 은행 창구 응대, 지급정지 통보, 이의제기 안내 등의 서술이 전혀 없다. 우리 기획서의 "은행 단계 어려움"을 검증할 자료로는 **쓸 수 없다.**

**경찰**
- **1단계 (통지)**: 집으로 고소장 유사 서면이 도달. 글쓴이는 **"고소장인가 그런 비슷한게"**라고 표현 — 자신이 받은 문서가 무엇인지조차 특정하지 못했다. 고소인 이름은 **모르는 사람**이어서 사건 파악이 원천적으로 불가능한 상태.
- **2단계 (출석)**: **"경찰서 출두하라 해서 일단 감"** — 사전 준비 없이, 무슨 사건인지 모른 채 출석.
- **3단계 (설명)**: 경찰이 그제서야 사건 개요를 알려줌. 즉 **정보 비대칭이 출석 시점까지 해소되지 않았다.**
- **4단계 (자각)**: **"이때 머릿속에서 모든 퍼즐이 맞춰졌다"** — 피의자 신분으로 조사실에 앉은 그 순간에야 자기가 3자사기에 끼워졌음을 처음 이해.
- **5단계 (소명)**: 쪽지·장소·시간·송금내역 제출.
- **6단계 (결과)**: **얼마 뒤 무혐의.**

**막힌 지점**: 절차적으로 크게 막힌 곳은 없다. 이 사례의 실제 병목은 **"무슨 일이 벌어졌는지 아무도 미리 알려주지 않는다"는 정보 공백**이었고, 그 공백은 경찰 조사 자리에서야 해소됐다. 반면 **소명 자체는 마찰 없이 수용**됐다 — 반려·보완요구·재제출 서술이 전혀 없다.

**기획서 "6단계 어려움"에 대한 함의**
- **검증되는 부분**: ① 아무 설명 없이 서면·소환이 날아오는 충격, ② 자신이 무슨 구조에 걸렸는지 스스로 파악 불가, ③ 준비 없이 조사에 임하게 됨 — 이 세 가지는 강하게 뒷받침된다.
