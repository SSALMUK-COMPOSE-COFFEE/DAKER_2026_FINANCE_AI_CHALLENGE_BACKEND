## 6. 기획서 인용 후보 문장 (원문 그대로)

> **"거래내역 쫙 훑고 수사관한테 꼬치꼬치 캐물어서 몇일 몇시 거래내역이냐고 물어서 시간 받아냄. 넥슨 고객센터에 해당일자 거래내역 뽑아달라고 요청해서 프린트, 내 통장 거래내역 당일자 쫙 프린트해서 가져감"**

→ 명의인은 **어떤 입금이 문제인지 스스로 알지 못한다**는 사실, 그리고 **문제 입금의 일시를 특정해야 비로소 증거 수집이 시작된다**는 절차 지식을 한 문장이 압축한다. 우리 서비스가 가장 먼저 물어야 할 질문이 무엇인지 알려준다.

> **"차분하고 덤덤하게 3자사기 구조 설명하고 증빙 딱딱 보여줌. 그리고 회사 다니고 있고 내 계좌는 입사 후 지금까지 급여통장으로 쓰고있다 하면서 명함 같이 제출"**

→ 성공한 소명의 3요소가 그대로 들어 있다: **구조 설명 + 거래·인도 증빙 + 계좌의 생활계좌 성격.** 우리 소명서 템플릿의 골격과 정확히 일치한다.

> **"한달뒤 통화옴. 경찰서 수사관이었는데 보이스피싱처럼 물어보길래 어딜 씨[…]려나 피싱질이야 […] 꺼져 라고함 // 근데 진짜 경찰관이었음;"**

→ 무고한 명의인이 사건을 **최초로 인지하는 순간의 혼란**을 보여준다. 정상적인 사람일수록 수사기관 연락을 피싱으로 의심하며, 이 첫 접촉이 관계를 망칠 수 있다. (욕설 부분 […] 처리)

