## 4. 글쓴이의 대응을 4분류에 매핑

| 분류 | 상태 | 내용 |
|---|---|---|
| **A. 거래가 실재했다** | **간접·반전형** | 사기범과의 5천원 거래는 실재하지만 30만원 입금과는 무관하다. 여기서 A의 역할은 뒤집힌다 — **"거래액 5천원 ≠ 입금액 30만원"이라는 불일치 자체가 "이 입금은 내 거래 대금이 아니다"의 증거**가 된다. 다만 글쓴이는 이를 제출용 증빙으로 정리하지 않았다(대화 로그·거래 게시글 보존 언급 없음). |
| **B. 물건을 실제로 넘겼다** | **성립 불가 / 부작위가 대체** | 30만원에 대응하는 물건을 넘긴 적이 없다. 전형 3자사기의 B(물품 인도 증빙)는 여기서 존재할 수 없다. 대신 **"아무것도 넘기지 않았다"는 부작위**가 방어의 핵심이다. B는 "무엇을 했는가"가 아니라 "무엇을 하지 않았는가"로 대체된다. |
| **C. 이 계좌는 원래 정상 생활계좌다** | **완전히 비어 있음** | 급여이체·공과금·통신비 등 생활계좌 증빙에 대한 언급이 전혀 없다. 대구은행 계좌를 굿즈 거래에 써왔다는 정황만 있을 뿐, 계좌의 정상성을 입증하려는 시도가 아예 없다. **4분류 중 공백이 가장 큰 항목.** |
| **D. 절차 메타** | **압도적으로 풍부 — 사실상 이 글의 전부** | 입금반환신청 안내 / 중계요청 실행 / 수취은행 → 송금은행 서류 릴레이 / 더치트 계좌 조회 및 신고자 쪽지 / 피해자 신원·정황 교차 확인 / 반환 실행 / 이후 피해자 커뮤니티 연결. **이 글은 소명서 사례가 아니라 절차 항해 사례집이다.** |

### 공백에 대한 지적

- **C가 완전 공백**인 이유는 명확하다. C는 "은행/수사기관을 설득해야 할 때" 필요한 재료인데, 이 사례에는 설득해야 할 상대(지급정지를 건 은행)가 애초에 없었다.
- **A가 약하고 B가 성립 불가**한 것도 같은 이유다. **정지 전 개입 사례에서는 A/B/C(사후 소명 재료)가 구조적으로 비고, D(절차 항해)가 지배한다.**
- **우리 서비스에 주는 경고**: 현재 문진이 A/B/C 중심(거래 증빙, 물품 인도 증빙, 계좌 정상성)으로만 설계돼 있다면, **이 사례의 이용자는 우리 서비스에 입력할 것이 하나도 없다.** 아직 정지되지 않은 사람은 "소명서를 써주는 서비스"의 대상이 아니기 때문이다. 그런데 이들이야말로 **개입 가치가 가장 높은 시점의 이용자**다.
- 부수적으로, 글쓴이가 A/B/C 재료를 **보존하지 않은 것 자체가 리스크**다. 사기범이 나중에 다른 피해자 명의로 다시 신고해 계좌가 정지된다면, 당시의 대화 로그·거래 내역이 없어 소명이 어려워진다. 예방 단계의 증거 보존이 필요한 이유다.

