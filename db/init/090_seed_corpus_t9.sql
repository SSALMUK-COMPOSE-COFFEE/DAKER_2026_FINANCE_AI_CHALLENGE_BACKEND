### "5천원짜리 물건에 30만원 입금 후 반환 요구" 수법의 의도 분석

이 수법은 다섯 겹으로 설계돼 있다.

**(1) 계좌번호 취득 비용의 최소화**
5천원 거래는 사기범 입장에서 손실이 거의 없으면서, 상대가 아무 경계 없이 계좌번호를 내주게 만드는 가장 값싼 방법이다. 중고거래에서 계좌번호는 "요청하면 주는 것"이므로 이 단계에서는 어떤 이상 신호도 발생하지 않는다.

**(2) 차액 = 실제 사기 수익, 그리고 명의인이 세탁 1단계를 대신 수행**
30만원은 사기범 돈이 아니라 별개 피해자의 돈이다. 명의인이 "차액 29만 5천원을 돌려준다"는 형식으로 송금하면, 자금은 **범죄 피해금이 아니라 정상적인 착오송금 반환금의 외양**을 갖게 된다. 즉 **명의인이 자금세탁의 첫 단계를 자기 손으로, 자발적으로, 선의로 수행하게 만드는 것**이 이 수법의 본질이다. 여기서 명의인 계좌는 대포통장을 대체하는 "빌려온 통장"이 된다.

**(3) '착오송금' 프레임의 도덕적 무기화**
"실수로 잘못 보냈다"는 서사는 법적으로 **부당이득 반환 의무**를 실제로 발생시킨다. 그래서 명의인은 거절할 때 *자기가 나쁜 짓을 하는 것 같은* 부담을 느낀다. 사기범은 이 정당성 감각을 지렛대로 쓴다. 여기에 **입금내역 캡쳐본**(실은 진짜 피해자가 보낸 것)까지 붙으면 서사는 완성된다.

**(4) 협박에 의한 시간 압박**
"경찰에 신고하겠다"는 협박은 이중으로 작동한다. ①명의인이 실제로 부당이득 상태이므로 신고가 무섭게 느껴지고, ②명의인 입장에서 신고는 **계좌 지급정지**로 직결된다. 사기범은 명의인이 은행 절차(며칠 소요)보다 즉시 송금(수 분)을 택하도록 시간축을 좁힌다.

**(5) 반환 계좌가 피해자 계좌와 두 자리만 다른 이유 (원문도 판단 유보)**
원문은 두 가지 가능성을 열어둔다 — "일부러 잘못된 계좌 알려줘놓고 자기 계좌로 돈 받으려던건지, 돌려막기하려고 피해자 계좌 알려주려다가 실수한건진 모름". 후자라면 사기범이 **여러 피해자를 동시에 굴리며 돌려막기**를 하다 계좌를 혼동했다는 뜻으로, 12번의 "피해 규모가 크다"는 진술과 정합적이다.

