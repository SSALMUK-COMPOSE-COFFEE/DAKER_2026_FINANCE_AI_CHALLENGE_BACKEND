## 5. 예방 관점의 시사점 — 「풀림」이 가질 수 있는 "정지 전" 기능

이 사례는 서비스의 시간축을 **"정지 후 구제" 한 점에서 "정지 전 → 정지 시점 → 정지 후" 라인으로 확장할 근거**다.

**5-1. 금액 불일치 트리거 (진입 문진 최상단 분기)**
"내 계좌에 들어온 금액이 실제 거래금액과 다른가?"를 첫 질문으로 둔다. 5천원 거래에 30만원 입금은 즉시 적색 신호다. 불일치가 감지되면 소명서 작성 플로우가 아니라 **"정지 전 대응" 플로우로 라우팅**한다. 이어서 "①상대가 반환을 요구하는가 ②특정 계좌를 지정했는가 ③압박·협박이 있는가"를 물으면 이 수법을 거의 확정적으로 식별할 수 있다.

**5-2. 반환 요구 대응 스크립트 생성기 (핵심 기능)**
상대에게 그대로 보낼 표준 답변문을 생성한다. 골자는 **"반환을 거부하는 것이 아니라, 반환 경로를 은행으로 고정하는 것"**이다.
- 기본형: "직접 송금은 어렵습니다. 거래하신 은행에 입금반환신청(착오송금 반환) 절차를 요청해 주시면 은행을 통해 정상적으로 반환됩니다."
- 협박 대응형: 경찰 신고 위협, "경찰서 가는 중" 사진, 입금내역 캡쳐본 제시 등 **이 사례에 나온 압박 유형별 대응 문구**를 템플릿화. 이 글의 원문 문장들이 그대로 템플릿 소스가 된다.

**5-3. 중계요청 준비 패키지 (수취인이 능동적으로 송금인을 찾는 경로)**
이 글의 대응 경로를 그대로 제품화한다.
- ①내 거래은행에서 발급받을 서류 체크리스트
- ②송금인 거래은행 창구에서 말할 요청문 초안 (은행별 명칭 매핑: 입금반환신청 / 착오송금 반환 / 중계요청 — **명칭이 은행마다 달라 창구에서 말이 안 통하는 것이 최대 병목**)
- ③창구가 "그건 송금인이 신청하는 겁니다"라며 거부할 때의 재요청 논리
- ④수취은행 ↔ 송금은행이 다를 때의 방문 순서 안내 (이 사례: 대구은행 → 신한은행)

**5-4. 더치트 자기계좌 조회 유도 = 조기경보 신호**
"내 계좌가 이미 사기계좌로 신고돼 있는가"는 **지급정지 임박도를 재는 가장 실용적인 지표**다. 등록돼 있으면 최우선 대응 플로우로 진입시키고, 신고자에게 보낼 연락 문안도 생성한다. 단, 이 사례에서 더치트 쪽지는 응답 지연으로 실패했으므로 **은행 경로와 병행**을 안내해야 한다.

**5-5. 사전 증거 스냅샷 — "예방 모드의 산출물이 구제 모드의 입력이 된다"**
아직 정지되지 않은 시점에 대화 로그·거래 게시글·입금 내역·상대 계정 정보를 타임스탬프와 함께 봉인 보관한다. 나중에 실제로 계좌가 정지되면 이 스냅샷이 **그대로 A/B/C 소명 재료로 전환**된다. 4장의 공백 지적을 제품으로 메우는 기능이며, 예방 기능과 구제 기능을 하나의 파이프라인으로 잇는 연결 고리다.

**5-6. 자금세탁 가담 위험 경고 인터스티셜**
"요구받은 계좌로 직접 송금하면, 당신이 범죄수익 전달책으로 의심받는 위치로 이동할 수 있습니다." — 예방 메시지의 단일 핵심 문장. 이 사례가 증명하듯 **송금 거부가 결과를 갈랐다.**

**5-7. (탐색적) 동일 사건 이용자 클러스터링**
이 글은 "피해자들이 오픈채팅방에 모여 있다"로 귀결된다. 계좌번호·상대 계정 식별자 해시 기준으로 동일 사기범 사건 이용자를 묶으면 대응 효율이 크게 오른다. 다만 개인정보·명예훼손 리스크가 커서 **법률 검토 전에는 제품화 금지** 영역으로 표시해 둔다.

