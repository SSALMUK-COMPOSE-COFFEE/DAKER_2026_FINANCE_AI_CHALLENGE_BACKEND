## 3. 계좌 지급정지가 실제로 있었는지

### 결론: **지급정지는 발생하지 않았다.** 원문에 지급정지·거래정지·계좌동결에 대한 언급이 **전혀 없다.** 다만 지급정지 직전 국면이었다.

**"직전 국면"이라고 보는 근거**

- **글쓴이 계좌가 이미 더치트에 사기계좌로 등록**돼 있었다("더치트에 내 계좌를 사기계좌로 등록한 (피해자로 추정되는)사람"). 이는 피해자가 이미 신고 채널에 진입했다는 뜻이고, 통상 그 다음 단계가 은행·경찰 신고를 통한 지급정지다.
- 사기범 역시 경찰 신고를 협박 카드로 쓰고 있었다.
- 즉 이 사례는 **"정지됐다가 풀린 사례"가 아니라 "정지 트리거가 당겨지기 전에 원인을 제거한 사례"**다.

### 지급정지를 피한 경로 (이 사례의 핵심)

**핵심 두 축 — ①돈을 옮기지 않았다 ②명의인이 먼저 은행으로 갔다**

**축 1. 자금을 계좌에 그대로 둔 것**
사기범 지정 계좌로 송금하지 않았기 때문에 30만원이 계좌에 남아 있었다. 이것이 결정적이다. 돈이 남아 있어야만 이후의 반환이 가능하고, "이 돈에 손대지 않았다"는 사실 자체가 명의인의 결백을 뒷받침한다.

**축 2. 수취인이 역방향으로 개시한 은행 중계요청**
통상 착오송금 반환신청은 **송금인**이 자기 거래은행에 신청하는 절차다. 이 사례는 **수취인(명의인)이 반대 방향으로 움직였다**는 점에서 특이하다. 실제 경로:

1. **더치트 쪽지** (병행 채널) — 자기 계좌를 사기계좌로 등록한 사람에게 직접 연락 시도 → **응답 지연으로 실질 실패**.
2. **본인 거래은행(대구은행) 방문** → 입금 건 관련 **서류 발급** ("대구은행에서 서류 이것저것 떼서"). 원문은 서류명을 특정하지 않는다 — 실무 확인이 필요한 공백.
3. **송금인 거래은행(신한은행) 방문** → 창구에 상황 설명 → **중계요청**.
4. 은행이 송금인(피해자)에게 연락을 중계 → **피해자와 연락 성사**.
5. 피해자로부터 **사기범과의 거래 정황을 확인**(= 이 사람이 진짜 송금인이자 피해자임을 검증).
6. **30만원 반환**.

**이 경로가 지급정지를 막은 메커니즘**
