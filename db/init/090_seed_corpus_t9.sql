## 7. 경고 — 일반화하면 위험한 지점

1. **"지급정지가 안 걸렸다"는 결과론이지 방법론이 아니다.**
   이 사례에서 계좌가 안 묶인 건 피해자가 아직 지급정지를 요청하지 않았거나 은행 조치 전이었기 때문일 수 있다. **이미 지급정지가 걸린 뒤라면 이 경로는 작동하지 않는다** — 정지된 계좌는 출금 자체가 안 되므로 자발적 반환이 물리적으로 불가능하다. 이 사례의 대응은 **철저히 시점 의존적**이다.

2. **수취인의 임의 반환은 그 자체로 법적 위험이 있다.**
   이 사례가 안전했던 결정적 이유는 **은행 중계를 거쳐 송금인의 신원과 거래 정황을 검증했기 때문**이다. 은행을 거치지 않고 개인적으로 확인해 반환하면 ①진짜 송금인이 아닌 사람에게 지급해 이중 변제 위험을 지고, ②통신사기피해환급법상 지급정지·채권소멸 절차가 이미 개시된 경우 임의 반환이 절차와 충돌할 수 있다. **"은행 없이 개인적으로 돌려줘도 된다"로는 절대 일반화하면 안 된다.**

3. **"중계요청"은 법정 제도명이 아니라 은행 창구 실무 관행이다.**
   은행마다 명칭·응대·요구 서류가 다르고 거부될 수도 있다. 또한 예금자보호법상 **착오송금 반환지원 제도(예금보험공사)는 2021-07-06 시행**으로 이 글 시점(2021-05-07)보다 뒤이며, 그마저도 **송금인이 신청하는 제도지 수취인이 신청하는 제도가 아니다.** 이 사례를 "제도가 보장하는 절차"로 소개하면 이용자를 오도한다. 제품화 전 **은행 실무·법령 교차검증 필수.**

4. **모든 금액 불일치가 사기는 아니다.**
   진짜 착오송금도 실제로 존재하고, 수취인에게는 부당이득 반환 의무가 있다. 서비스가 "절대 돌려주지 마라"를 무조건 출력하면 진짜 착오송금 피해자에게 손해를 끼치고 우리 쪽 법적 리스크도 생긴다. **출력은 반드시 "직접 송금 대신 은행 절차로"여야 하며, "반환 자체를 거부하라"가 되어서는 안 된다.** 원문도 정확히 이 선을 지키고 있다 — "진짜 실수로 입금한 경우라면 은행가서 입금반환신청하면 은행통해서 돈 돌려받을 수 있으니까 그렇게 안내해줘".

5. **자료 신뢰도의 한계.**
   2021년 익명 커뮤니티의 1인칭 후기이며 검증 불가. 은행명·금액·절차는 글쓴이 기억에 의존한다. **댓글 5개 중 3개는 삭제됐고 남은 2개는 실무 정보가 없다.** 본문의 "댓글로 알려주는대로"는 **이 글의 댓글이 아니라 글쓴이가 다른 곳(핫게)에서 받은 조언**을 가리킨다. 절차 근거로 인용하려면 반드시 은행 실무·법령 자료로 보강해야 한다.

6. **개인 특정 정보 취급 주의.**
   원문에는 트위터 계정 링크 2건이 인용돼 있으나 **지시에 따라 추적하지 않았다.** 사기범으로 지목된 계정 정보는 검증되지 않은 제3자 주장이므로 **기획서·제품에 옮기지 말 것**(명예훼손·개인정보 리스크).

