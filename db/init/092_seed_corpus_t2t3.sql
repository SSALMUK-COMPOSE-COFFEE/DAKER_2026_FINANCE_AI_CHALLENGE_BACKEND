검사가 경찰의 보완수사 지휘 없이 직접 피의자를 조사하는 것이 반드시 기소를 의미하는 것은 아니라는 분석이 많았다. 피해자의 이의제기가 있을 경우 검사가 직접 사실관계를 다시 확인하는 경우가 있다는 것이다.
