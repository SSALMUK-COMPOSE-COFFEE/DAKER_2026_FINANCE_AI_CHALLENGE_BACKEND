-- 097_map_clause.sql · 유형별로 다툴 조항 매핑 (case_types.clause)
--
-- 근거는 통신사기피해환급법 제7조 제1항이다. 명의인이 이의를 제기할 수 있는 사유가
-- 세 갈래로 나뉘어 있고, 유형마다 어느 갈래로 다투는지가 다르다.
--
--   1호  해당 계좌가 사기이용계좌가 아니라는 사실을 소명
--   2호  소멸될 채권을 재화 또는 용역의 공급에 대한 대가로 받았거나
--        그 밖에 정당한 권원에 의하여 취득한 것임을 객관적 자료로 소명
--        (단서 — 명의인이 알았거나 중대한 과실로 알지 못한 경우는 제외)
--   3호  해당 계좌가 피해금 편취를 위하여 이용된 계좌가 아니라는 사실을 소명
--
-- 갈림길은 단순하다. 무언가를 팔거나 제공하고 그 대가로 받았으면 2호,
-- 거래 자체가 없이 계좌만 경유지로 쓰였으면 1호·3호다.
-- 2호 단서의 "중대한 과실"은 대법원 2024다216187 이 해석했다 — 조금만 주의를
-- 기울였다면 쉽게 알 수 있었는데도 그러지 않은 경우이고, 증명책임은 피해자에게 있다.
--
-- 범위 밖 유형(T12·T13·T14·T16)은 비워 둔다. 소명서를 만들지 않으므로 다툴 조항도 없다.
--
-- ⚠ 이 매핑은 조문 구조를 따라 정리한 것이지 변호사 검토를 받은 것이 아니다.
--   실제 서면에 조항을 적기 전에 전문가 확인이 필요하다.

-- ── 재화·용역의 대가로 받은 유형 → 제7조 제1항 제2호
UPDATE case_types SET clause = '법 제7조 제1항 제2호'
WHERE code IN ('T1','T2','T3','T4','T5','T6','T7','T15');

-- ── 거래 없이 계좌만 경유·도용된 유형 → 제7조 제1항 제1호·제3호
UPDATE case_types SET clause = '법 제7조 제1항 제1호·제3호'
WHERE code IN ('T9','T10','T11');

-- ── 초과입금형은 두 갈래가 같이 걸린다
--    거래분은 2호(물건 대금), 초과분은 3호(내 거래 대금이 아님)로 나눠 다툰다
UPDATE case_types SET clause = '법 제7조 제1항 제2호(거래분)·제3호(초과분)'
WHERE code = 'T8';

-- ── 범위 밖 유형은 비운다
UPDATE case_types SET clause = NULL
WHERE out_of_scope;
